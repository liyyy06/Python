# Arithmetic operations
print(10 + 3)  # addition
print(10 - 3)  # subtraction
print(10 * 3)  # multiplication
print(10 / 3)  # divison
print(10 // 3) #integer
print(10 % 3)  # modulus
print(10 ** 3) # exponential
print(10 // 3) # floor division

x = 10
x += 3
print(x)       # 13

x = 5
x -= 2
print(x)       # 3

# Volume of cube
side = 3
volume = side**3
print("Volume of cube: ", volume)

# Boolean (< > <= >= == !=)
print(2 > 3)   # False
print(9 < 10)  # True
print(7 == 8)  # False
print(7 != 8)  # True

print(len("cat") == len("dog")) # True
print("P in Python: ", "P" in "Python") # True
print("1 is 2: ", 1 is 2) # False
